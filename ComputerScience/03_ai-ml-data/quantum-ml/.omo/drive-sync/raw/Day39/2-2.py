# ============================================================
# Part 2. Cost Hamiltonian 구현
# Lab 2. Cost Layer 생성
# ============================================================

from qiskit import QuantumCircuit
from qiskit.circuit import Parameter


# ------------------------------------------------------------
# Step 1. Cost Parameter 생성
# ------------------------------------------------------------

gamma = Parameter("γ")


# ------------------------------------------------------------
# Step 2. 2-Qubit Quantum Circuit 생성
# ------------------------------------------------------------

qc = QuantumCircuit(2)


# ------------------------------------------------------------
# Step 3. Cost Hamiltonian 확인
#
# H_C = Z0 Z1
#
# Z0 Z1
#   ↓
# RZZ Gate
# ------------------------------------------------------------


# ------------------------------------------------------------
# Step 4. Cost Layer 생성
# ------------------------------------------------------------

qc.rzz(
    2 * gamma,   # Rotation Angle
    0,           # Qubit 0
    1            # Qubit 1
)


# ------------------------------------------------------------
# Step 5. Circuit 출력
# ------------------------------------------------------------

print("=== Cost Layer Circuit ===")
print(qc.draw())


# ------------------------------------------------------------
# Step 6. Circuit Parameter 확인
# ------------------------------------------------------------

print("\n=== Circuit Parameters ===")
print(qc.parameters)


# ------------------------------------------------------------
# Step 7. Gate 개수 확인
# ------------------------------------------------------------

print("\n=== Gate Count ===")
print(qc.count_ops())


# ------------------------------------------------------------
# Step 8. Lab 결과
# ------------------------------------------------------------

print("\n=== Lab 2 Complete ===")
print("Cost Hamiltonian : Z0 Z1")
print("Cost Gate        : RZZ")
print("Rotation Angle   : 2γ")
print("Applied Qubits   : q0, q1")
print("Cost Layer       : Created")